// 竞品分析：发给 AI 的话。评价、标签、统计都放在附件“材料.txt”里，说明写在正文里。
const JSON_ONLY = "只回复一个 JSON 代码块，不要其他文字。";

export const tagPrompt = () => [
  "你是电商评价分析助手。附件“材料.txt”里是一个淘宝商品的买家评价，每行一条，格式：#编号 [规格] 评价内容。",
  "逐条分析，给每条评价打标签：",
  "- s：整体态度，1 满意，0 一般，-1 不满意",
  "- good：买家满意的点（短标签，2～8 个字，如“保温效果好”“做工精细”），没有就空数组",
  "- bad：买家不满意的点（短标签，如“杯盖漏水”“有异味”），没有就空数组",
  "- need：买家的用途、使用场景或需求（如“上班带饭”“送礼”），没有就空数组",
  "- who：评价里能看出的买家身份（如“学生”“宝妈”“老人”），没有就空数组",
  "要求：标签用中文，意思相同的用同一个说法；只根据评价原文，不要猜；每一条都要有结果，编号不能漏，也不能多。",
  `${JSON_ONLY}格式：[{"i":1,"s":1,"good":["保温效果好"],"bad":[],"need":["上班用"],"who":[]}]`,
].join("\n");

export const qaPrompt = () => [
  "附件“材料.txt”里是一个淘宝商品“问大家”里买家提的问题，每行一条，格式：#编号 问题 ｜ 回答。",
  "给每个问题归纳一个主题（2～8 个字，如“是否漏水”“尺寸大小”“保温时间”），意思相同的用同一个说法；worry 表示这个问题是不是在表达担心、顾虑。",
  `每一条都要有结果，编号不能漏。${JSON_ONLY}格式：[{"i":1,"topic":"是否漏水","worry":true}]`,
].join("\n");

export const vocabPrompt = () => [
  "附件“材料.txt”里是从买家评价里打出来的标签和出现次数（JSON），分五类：good 满意点、bad 不满意点、need 用途和需求、who 买家身份、qa 问大家的主题。",
  "请把每一类里意思相同或很接近的标签合并成一个归类名（2～8 个字，用最常见、最好懂的说法）。每个标签都要给出归类名，标签原样作为 key；不同类之间不要混。",
  `${JSON_ONLY}格式：{"good":{"保温好":"保温效果好"},"bad":{},"need":{},"who":{},"qa":{}}`,
].join("\n");

export const writePrompt = (hasOurs, oursManual) => [
  "你是资深电商运营和产品经理。附件“材料.txt”里是几个淘宝 / 天猫商品的买家评价统计（程序统计的，数字准确），role 为 ours 的是“我们的产品”，rival 是竞品。",
  hasOurs ? (oursManual ? "我们的产品没有评价数据，只有我们自己填写的产品信息（ours.manual），对比时以它为准。" : "") : "这次没有提供我们的产品，compare 里写“未提供我们的产品”。",
  "请写一份竞品分析结论：简体中文，具体、能直接照着做；每条结论都要以统计数据为依据（写出百分比或条数）；不要编造统计里没有的数据和事实。",
  "products 里 key 用材料里的 key；pains 是几个商品共同的痛点；compare 是我们和竞品比；suggestions 分产品改进、详情页和主图、主打卖点、要提前回答的问题、价格和规格五类。",
  `${JSON_ONLY}格式：`,
  JSON.stringify({
    summary: "三到五句话的总体结论",
    products: [{ key: "p1", positioning: "一句话定位", strengths: ["优势"], weaknesses: ["短板"] }],
    needs: ["买家最核心的需求或使用场景，按重要程度排"],
    pains: [{ point: "共性痛点", evidence: "依据（引用数据）", opportunity: "我们的机会" }],
    compare: { better: ["我们比竞品好的地方"], worse: ["我们不如竞品的地方"], gaps: ["竞品买家抱怨、我们可以解决的点"] },
    suggestions: { product: ["产品改进"], detail: ["详情页 / 主图怎么改"], points: ["建议主打的卖点"], faq: ["详情页里要提前回答的问题"], price: ["价格 / 规格建议"] },
    risks: ["要注意的风险"],
  }),
].filter(Boolean).join("\n");
